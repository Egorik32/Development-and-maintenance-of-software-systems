import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.LinkedHashSet;
import org.eclipse.emf.common.util.URI;
import org.eclipse.emf.ecore.resource.Resource;
import org.eclipse.emf.ecore.resource.impl.ResourceSetImpl;
import org.eclipse.emf.ecore.xmi.impl.XMIResourceFactoryImpl;
import org.eclipse.fx.ide.jdt.ui.internal.handler.AbstractAntHandler.BuildConfiguration;
import org.eclipse.fx.ide.jdt.ui.internal.handler.AntTemplate;
import org.eclipse.fx.ide.jdt.ui.internal.handler.SetupDirectory;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.AntTask;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.AntTasksFactory;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.AntTasksPackage;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.Deploy;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.parameters.Application;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.parameters.Info;
import org.eclipse.fx.ide.jdt.ui.internal.editors.model.anttasks.parameters.ParametersFactory;

public class EfxBuildGenerator {
    public static void main(String[] args) throws Exception {
        File project = new File(args[0]).getCanonicalFile();
        BuildConfiguration config = (BuildConfiguration) BuildConfiguration.class.getDeclaredConstructors()[0].newInstance(new Object[] {null});
        config.origProjectRefSourceDirs = new LinkedHashSet<>();
        config.projectRefSourceDirs = new LinkedHashSet<>();
        config.origProjectSourceDirs = new LinkedHashSet<>();
        config.projectSourceDirs = new LinkedHashSet<>();
        config.origExternalLibs = new LinkedHashSet<>();
        config.externalLibs = new LinkedHashSet<>();
        for (String dir : new String[] {"src/main/java", "src/main/resources"}) {
            config.origProjectSourceDirs.add(new SetupDirectory(project, new File(dir)));
            config.projectSourceDirs.add(dir);
        }
        config.sourceCompliance = "1.8";
        config.targetCompliance = "1.8";
        config.projectEncoding = "UTF-8";
        config.projectName = "CityParks";
        config.buildDirectory = "native-build";
        config.jfxjar = new File(System.getProperty("java.home"), "lib/ext/jfxrt.jar").getAbsolutePath();
        AntTasksFactory factory = AntTasksFactory.eINSTANCE;
        ParametersFactory parameters = ParametersFactory.eINSTANCE;
        AntTask task = factory.createAntTask();
        task.setBuildDirectory("native-build");
        task.setSignjar(factory.createSignJar());
        Deploy deploy = factory.createDeploy();
        Application application = parameters.createApplication();
        application.setName("CityParks");
        application.setMainclass("com.example.cityparks.MainApp");
        application.setVersion("1.0");
        deploy.setApplication(application);
        Info info = parameters.createInfo();
        info.setTitle("CityParks");
        info.setVendor("CityParks Lab");
        deploy.setInfo(info);
        deploy.setPackagingFormat(args.length > 1 ? args[1] : "image");
        deploy.setVerbose(true);
        task.setDeploy(deploy);
        config.task = task;
        File build = new File(project, "native-build");
        build.mkdirs();
        String generated = new AntTemplate().generateAnt(config);
        Files.write(new File(build, "build.generated.xml").toPath(), generated.getBytes(StandardCharsets.UTF_8));
        // Tutorial part 7 requires the project directory on the Ant icon resource path and an explicit version.
        String customized = generated.replace("<filelist>", "<filelist>\n<file name=\"${basedir}\"/>");
        customized = customized.replace("mainClass=\"com.example.cityparks.MainApp\"", "mainClass=\"com.example.cityparks.MainApp\" version=\"1.0\"");
        customized = customized.replace("<delete file=\"dist\"/>", "<delete dir=\"dist\"/>");
        customized = customized.replace("<delete file=\"deploy\" />", "<delete dir=\"deploy\" />");
        Files.write(new File(build, "build.xml").toPath(), customized.getBytes(StandardCharsets.UTF_8));
        ResourceSetImpl resources = new ResourceSetImpl();
        resources.getResourceFactoryRegistry().getExtensionToFactoryMap().put("fxbuild", new XMIResourceFactoryImpl());
        resources.getPackageRegistry().put(AntTasksPackage.eNS_URI, AntTasksPackage.eINSTANCE);
        Resource resource = resources.createResource(URI.createFileURI(new File(project, "build.fxbuild").getAbsolutePath()));
        resource.getContents().add(task);
        resource.save(null);
        System.out.println("Generated by e(fx)clipse 2.4.0 AntTemplate: " + new File(build, "build.xml"));
    }
}
